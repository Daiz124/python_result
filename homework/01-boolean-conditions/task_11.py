# В магазине три кассы. Про каждую вводится ответ, открыта ли она: «да» или «нет». Выведите, верно
# ли, что открыта ровно одна касса.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     нет
#     да
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): нет
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): нет
#     True
# Пример 2
#   ввод:
#     да
#     да
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): да
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): нет
#     False
# Пример 3
#   ввод:
#     нет
#     нет
#     нет
#   в терминале:
#     Касса 1 открыта (да/нет): нет
#     Касса 2 открыта (да/нет): нет
#     Касса 3 открыта (да/нет): нет
#     False
# Пример 4
#   ввод:
#     да
#     да
#     да
#   в терминале:
#     Касса 1 открыта (да/нет): да
#     Касса 2 открыта (да/нет): да
#     Касса 3 открыта (да/нет): да
#     False

# Решение
kassa1=input("Касса 1 открыта (да/нет): ")
kassa2=input("Касса 2 открыта (да/нет): ")
kassa3=input("Касса 3 открыта (да/нет): ")
print((kassa1=="да" and kassa2=="нет" and kassa3=="нет") or (kassa2=="да" and kassa1=="нет" and kassa3=="нет") or (kassa3=="да" and kassa1=="нет" and kassa2=="нет"))